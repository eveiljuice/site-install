adapter_apache_modules() {
  echo "rewrite headers deflate expires proxy_fcgi setenvif ssl"
}

# adapter_vhost_template <domain> <webroot> <project_path> <php_mode> <ssl>
adapter_vhost_template() {
  local domain="$1" webroot="$2" project_path="$3" php_mode="$4" ssl="$5"
  cat <<EOF
# Generated by site-install on $(date -Iseconds)
<VirtualHost *:80>
    ServerName ${domain}
    ServerAlias www.${domain}
    DocumentRoot ${webroot}

    <Directory ${webroot}>
        Options -Indexes +FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>

    <FilesMatch "\.php$">
        SetHandler "proxy:unix:/run/php/php8.1-fpm.sock|fcgi://localhost"
    </FilesMatch>

    ErrorLog \${APACHE_LOG_DIR}/${domain}-error.log
    CustomLog \${APACHE_LOG_DIR}/${domain}-access.log combined
</VirtualHost>
EOF
}

