adapter_post_install() {
  local project_path="$1"
  # composer install если есть composer.json
  if [[ -f "$project_path/composer.json" ]] && command -v composer >/dev/null 2>&1; then
    (cd "$project_path" && composer install --no-dev --optimize-autoloader 2>&1) || true
  fi
}

adapter_migrate() {
  local project_path="$1"
  (cd "$project_path" && php database/migrate.php)
}
