#!/usr/bin/env bash
# php-mysql.sh — адаптер для PHP+MySQL+Apache (elsesserandco)

set -euo pipefail

adapter_name() {
  echo "php-mysql"
}

adapter_matches() {
  local stack_json="$1"
  local entry; entry=$(echo "$stack_json" | jq -r '.entry_type' 2>/dev/null)
  local db;    db=$(echo "$stack_json"    | jq -r '.db' 2>/dev/null)
  [[ "$entry" == "php" && "$db" == "mysql" ]]
}

adapter_describe() {
  cat <<EOF
PHP 8.1 + FPM
MySQL 8 / MariaDB
Apache 2.4 + mod_rewrite
Let's Encrypt (опционально)
EOF
}

